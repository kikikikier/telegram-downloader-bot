"""User-facing status replicas for the Telegram downloader bot."""


def _build_replicas(openers: tuple[str, ...], middles: tuple[str, ...], closers: tuple[str, ...]) -> tuple[str, ...]:
    messages: list[str] = []
    seen: set[str] = set()
    for opener in openers:
        for middle in middles:
            for closer in closers:
                text = f"{opener} {middle} {closer}"
                if text in seen:
                    continue
                seen.add(text)
                messages.append(text)
                if len(messages) == 200:
                    return tuple(messages)
    raise ValueError("replica source parts did not produce 200 unique messages")


